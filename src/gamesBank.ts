// ========================================================
// دالة الاختيار الذكي بدون تكرار للأسئلة
// ========================================================
export function getNonRepeatingBatch<T extends { id: string }>(
  pool: T[],
  seenIds: string[],
  count: number
): { selected: T[]; updatedSeenIds: string[]; wasReset: boolean; cycleNumber: number } {
  if (!pool || pool.length === 0) {
    return {
      selected: [],
      updatedSeenIds: seenIds,
      wasReset: false,
      cycleNumber: 1
    };
  }

  // تصفية الأسئلة التي لم يشاهدها الطالب
  const unseen = pool.filter(item => !seenIds.includes(item.id));

  let wasReset = false;
  let candidatePool: T[] = unseen;
  let baseSeenIds = [...seenIds];

  // إذا كانت الأسئلة المتبقية غير كافية لجولة كاملة، ننهي الدورة ونبدأ دورة جديدة
  if (unseen.length < count) {
    candidatePool = [...pool];
    baseSeenIds = [];
    wasReset = true;
  }

  // خلط العناصر عشوائيًا (Fisher-Yates)
  const shuffled = [...candidatePool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const selected = shuffled.slice(0, Math.min(count, shuffled.length));
  const newSeenIds = [...baseSeenIds, ...selected.map(s => s.id)];

  const cycleNumber = Math.floor(seenIds.length / Math.max(1, pool.length)) + 1;

  return {
    selected,
    updatedSeenIds: newSeenIds,
    wasReset,
    cycleNumber
  };
}
